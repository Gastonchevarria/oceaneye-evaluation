def get_meta_api_key() -> str:
    """Resolve META_API_KEY or MODEL_API_KEY from environment or ~/.hermes/.env."""
    key = os.getenv("META_API_KEY") or os.getenv("MODEL_API_KEY") or ""
    if key:
        return key.strip().strip("\"'")
    env_path = os.path.expanduser("~/.hermes/.env")
    if os.path.exists(env_path):
        try:
            with open(env_path, "r", encoding="utf-8") as f:
                for line in f:
                    if line.startswith("META_API_KEY="):
                        return line.strip().split("=", 1)[1].strip().strip("\"'")
        except Exception:
            pass
    return ""


def _record_telemetry(
    model: str,
    endpoint: str,
    request_id: str,
    latency_ms: float,
    prompt_tokens: int = 0,
    completion_tokens: int = 0,
    reasoning_tokens: int = 0,
    extra: Optional[Dict[str, Any]] = None,
) -> None:
    META_TELEMETRY_LEDGER["total_requests"] += 1
    META_TELEMETRY_LEDGER["total_prompt_tokens"] += int(prompt_tokens)
    META_TELEMETRY_LEDGER["total_completion_tokens"] += int(completion_tokens)
    META_TELEMETRY_LEDGER["total_reasoning_tokens"] += int(reasoning_tokens)
    if model == "muse-image-1.0":
        META_TELEMETRY_LEDGER["total_images_generated"] += 1
    if model == "sam-3.1":
        META_TELEMETRY_LEDGER["total_sam31_segmentations"] += 1

    entry = {
        "timestamp_utc": datetime.now(timezone.utc).isoformat(),
        "model": model,
        "endpoint": endpoint,
        "request_id": request_id,
        "latency_ms": round(latency_ms, 2),
        "prompt_tokens": prompt_tokens,
        "completion_tokens": completion_tokens,
        "reasoning_tokens": reasoning_tokens,
    }
    if extra:
        entry.update(extra)
    META_TELEMETRY_LEDGER["recent_calls"].insert(0, entry)
    if len(META_TELEMETRY_LEDGER["recent_calls"]) > 50:
        META_TELEMETRY_LEDGER["recent_calls"] = META_TELEMETRY_LEDGER["recent_calls"][:50]


async def call_meta_muse_chat(
    messages: List[Dict[str, str]],
    model: str = "muse-wonder-1.0",
    temperature: float = 0.2,
    max_tokens: int = 8192,
) -> Dict[str, Any]:
    """
    Execute a chat completion against https://api.meta.ai/v1/chat/completions
    using Meta's flagship `muse-wonder-1.0` or `muse-spark-1.3` models.
    Returns structured dict with `content`, `model`, `request_id`, `usage`, and `latency_ms`.
    """
    api_key = get_meta_api_key()
    if not api_key:
        raise RuntimeError("META_API_KEY not configured")

    t0 = time.perf_counter()
    headers = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
        "User-Agent": "OceanEye-MetaHackathon/1.0",
    }

    models_to_try = [model]
    if model != "muse-wonder-1.0":
        models_to_try.append("muse-wonder-1.0")
    else:
        models_to_try.append("muse-spark-1.3")

    last_err: Optional[Exception] = None
    async with httpx.AsyncClient(timeout=90.0) as client:
        for candidate_model in models_to_try:
            try:
                payload = {
                    "model": candidate_model,
                    "messages": messages,
                    "temperature": temperature,
                    "max_tokens": max_tokens,
                }
                resp = await client.post(
                    f"{META_BASE_URL}/chat/completions",
                    headers=headers,
                    json=payload,
                )
                if resp.status_code != 200:
                    logger.warning(f"Meta API {candidate_model} HTTP {resp.status_code}: {resp.text[:250]}")
                    continue

                data = resp.json()
                latency_ms = round((time.perf_counter() - t0) * 1000.0, 2)
                choice = (data.get("choices") or [{}])[0]
                content = (choice.get("message") or {}).get("content") or ""
                usage = data.get("usage") or {}
                reasoning_tokens = (usage.get("completion_tokens_details") or {}).get("reasoning_tokens", 0)
                req_id = data.get("id", f"meta-{int(time.time())}")

                _record_telemetry(
                    model=candidate_model,
                    endpoint="/v1/chat/completions",
                    request_id=req_id,
                    latency_ms=latency_ms,
                    prompt_tokens=usage.get("prompt_tokens", 0),
                    completion_tokens=usage.get("completion_tokens", 0),
                    reasoning_tokens=reasoning_tokens,
                )

                if content.strip():
                    return {
                        "content": content.strip(),
                        "model": candidate_model,
                        "request_id": req_id,
                        "latency_ms": latency_ms,
                        "usage": {
                            "prompt_tokens": usage.get("prompt_tokens", 0),
                            "completion_tokens": usage.get("completion_tokens", 0),
                            "reasoning_tokens": reasoning_tokens,
                            "total_tokens": usage.get("total_tokens", 0),
                        },
                    }
            except Exception as e:
                last_err = e
                logger.warning(f"Meta API call error on {candidate_model}: {e}")

    raise RuntimeError(f"All Meta Muse models failed: {last_err}")


async def generate_muse_forensic_dossier(
    sar_target: SarVesselDetection,
    scene_id: str = "S1A_IW_GRDH_1SDV_2026_MILE201",
) -> Dict[str, Any]:
    """
    Generate an end-to-end cryptographic forensic dossier powered by Meta `muse-wonder-1.0`,
    verified through the OceanEye Neuro-Symbolic Validator (0.00% numerical hallucination),
    and signed with LAYA Ed25519.
    """
    base_dossier = generate_forensic_dossier(sar_target=sar_target, scene_id=scene_id)
    laya_cert = seal_forensic_evidence_laya(sar_target=sar_target, scene_id=scene_id)

    signed_dist, nearest_pt, boundary_status = calculate_distance_to_eez_boundary(
        sar_target.lat, sar_target.lon
    )
    verdict = evaluate_maritime_case(
        distance_to_eez_nm=signed_dist,
        classification=sar_target.classification,
    )

    ev_vector = EvidenceVector(
        target_id=sar_target.id,
        lat=sar_target.lat,
        lon=sar_target.lon,
        length_m=sar_target.length_m,
        beam_m=sar_target.beam_m,
        peak_rcs_db=sar_target.peak_rcs_db,
        snr_db=sar_target.snr_db,
        distance_to_eez_nm=signed_dist,
        classification=sar_target.classification,
        boundary_status=boundary_status,
        legal_verdict=verdict,
    )

    system_prompt = (
        "Sos el Auditor Forense Naval de OceanEye impulsado por Meta Muse Wonder 1.0. "
        "Redactá un dictamen pericial formal en español para el Tribunal Marítimo Internacional y la "
        "Prefectura Naval Argentina (PNA) utilizando EXCLUSIVAMENTE los valores numéricos exactos del vector de evidencia."
    )
    user_prompt = (
        f"Redactá un dictamen pericial de 3 oraciones concisas sobre el objetivo radar `{sar_target.id}` "
        f"detectado en la escena `{scene_id}`:\n"
        f"- Latitud exacta: {sar_target.lat:.4f}\n"
        f"- Longitud exacta: {sar_target.lon:.4f}\n"
        f"- Distancia al límite ZEE (Milla 200): {abs(signed_dist):.2f} NM ({boundary_status})\n"
        f"- Eslora estimada: {sar_target.length_m:.1f} metros de eslora\n"
        f"- Firma Radar RCS: {sar_target.peak_rcs_db:.1f} dB\n"
        f"- Clasificación morfológica: {sar_target.classification}\n"
        f"- Tipificación legal: {verdict.infraction_code} (CONVEMAR / Ley Federal de Pesca)\n"
        "Incluí explícitamente esos 5 valores numéricos exactos (latitud, longitud, distancia en NM, eslora en metros y RCS en dB) sin mencionar ningún otro número ni medida adicional."
    )

    muse_meta: Dict[str, Any] = {}
    try:
        muse_res = await call_meta_muse_chat(
            messages=[
                {"role": "system", "content": system_prompt},
                {"role": "user", "content": user_prompt},
            ],
            model="muse-wonder-1.0",
            temperature=0.1,
            max_tokens=8192,
        )
        raw_narrative = muse_res["content"]
        muse_meta = {
            "provider": "Meta Model API (https://api.meta.ai/v1)",
            "model": muse_res["model"],
            "request_id": muse_res["request_id"],
            "latency_ms": muse_res["latency_ms"],
            "usage": muse_res["usage"],
        }
    except Exception as e:
        logger.warning(f"Fallback narrative due to Meta API error: {e}")
        raw_narrative = (
            f"Detección radar SAR confirmada para el objetivo {sar_target.id} en latitud {sar_target.lat:.4f}, "
            f"longitud {sar_target.lon:.4f}, a {abs(signed_dist):.2f} NM del límite de la ZEE Argentina ({boundary_status}). "
            f"El eco metálico registra una eslora de {sar_target.length_m:.1f} m y RCS de {sar_target.peak_rcs_db:.1f} dB "
            f"sin transpondedor AIS activo, encuadrando en {verdict.infraction_code}."
        )
        muse_meta = {
            "provider": "Deterministic Fallback",
            "model": "deterministic-rule-engine",
            "error": str(e),
        }

    ns_validation = validate_legal_narrative(
        raw_narrative,
        ev_vector,
    )

    dossier_dict = base_dossier.model_dump()
    dossier_dict["laya_ed25519_certificate"] = laya_cert.model_dump()
    dossier_dict["meta_muse_forensic_analysis"] = {
        "meta_api_telemetry": muse_meta,
        "raw_muse_narrative": raw_narrative,
        "sanitized_verified_narrative": ns_validation.sanitized_legal_text,
        "neuro_symbolic_validation": ns_validation.model_dump(),
    }
    return dossier_dict


def _parse_sam31_sse_output(sse_text: str) -> Dict[str, Any]:
    """
    Parse the SSE stream from `sam-3.1` on `POST https://api.meta.ai/v1/responses`
    to extract response_id, bounding boxes `<|box;x1=...;y1=...;x2=...;y2=...;w=...;h=...|>`
    and lossless RLE masks `<|mask;x=...;y=...;data=...|>`!
    """
    response_id = ""
    deltas: List[str] = []
    for line in sse_text.splitlines():
        if not line.startswith("data: "):
            continue
        payload_str = line[6:].strip()
        if not payload_str or payload_str == "[DONE]":
            continue
        try:
            evt = json.loads(payload_str)
            if not response_id and isinstance(evt.get("response"), dict):
                response_id = evt["response"].get("id", "")
            if evt.get("type") == "response.output_text.delta":
                deltas.append(evt.get("delta", ""))
            elif evt.get("type") == "response.completed" and isinstance(evt.get("response"), dict):
                response_id = evt["response"].get("id", response_id)
        except Exception:
            pass

    full_stream_text = "".join(deltas)
    boxes: List[Dict[str, int]] = []
    for m in re.finditer(
        r"<\|box;x1=(\d+);y1=(\d+);x2=(\d+);y2=(\d+);w=(\d+);h=(\d+)\|>",
        full_stream_text,
    ):
        boxes.append({
            "x1": int(m.group(1)),
            "y1": int(m.group(2)),
            "x2": int(m.group(3)),
            "y2": int(m.group(4)),
            "image_width": int(m.group(5)),
            "image_height": int(m.group(6)),
            "bbox_width_px": int(m.group(3)) - int(m.group(1)),
            "bbox_height_px": int(m.group(4)) - int(m.group(2)),
        })

    masks: List[Dict[str, Any]] = []
    for m in re.finditer(r"<\|mask;x=(\d+);y=(\d+);data=([^|]+)\|>", full_stream_text):
        rle_data = m.group(3)
        masks.append({
            "x": int(m.group(1)),
            "y": int(m.group(2)),
            "encoding": "lossless_rle",
            "rle_length_chars": len(rle_data),
            "rle_preview": rle_data[:120] + ("..." if len(rle_data) > 120 else ""),
        })

    return {
        "response_id": response_id,
        "detections_count": len(boxes),
        "bounding_boxes": boxes,
        "lossless_masks": masks,
        "raw_token_length": len(full_stream_text),
    }


async def reconstruct_and_segment_vessel_meta(
    sar_target: SarVesselDetection,
    prompt_target: str = "ship",
) -> Dict[str, Any]:
    """
    Full multimodal Meta Model API pipeline:
    1. Calls `muse-image-1.0` to synthesize an overhead satellite optical/SAR reconstruction
       of the detected dark vessel based on its physical radar cross-section, length, beam, and class.
    2. Uploads the reconstructed satellite frame to `POST https://api.meta.ai/v1/files` (`purpose=user_data`).
    3. Executes `sam-3.1` on `POST https://api.meta.ai/v1/responses` (`mask_encoding=lossless`)
       to segment the exact vessel hull bounding box and lossless RLE mask.
    """
    api_key = get_meta_api_key()
    if not api_key:
        raise RuntimeError("META_API_KEY not configured")

    t_start = time.perf_counter()
    prompt = (
        f"Top-down nadir satellite surveillance optical and synthetic aperture radar composite view "
        f"of an industrial {sar_target.classification.replace('_', ' ').lower()} vessel "
        f"({sar_target.length_m:.0f}m length, {sar_target.beam_m:.0f}m beam, "
        f"radar cross section {sar_target.peak_rcs_db:.1f} dB) operating in the South Atlantic ocean "
        f"near Mile 201 with visible white hydrodynamic wake, high contrast scientific maritime imagery."
    )

    headers_json = {
        "Authorization": f"Bearer {api_key}",
        "Content-Type": "application/json",
        "User-Agent": "OceanEye-MetaHackathon/1.0",
    }

    async with httpx.AsyncClient(timeout=60.0) as client:
        # Step 1: Generate satellite target image with `muse-image-1.0`
        t_img0 = time.perf_counter()
        img_resp = await client.post(
            f"{META_BASE_URL}/images/generations",
            headers=headers_json,
            json={
                "model": "muse-image-1.0",
                "prompt": prompt,
                "n": 1,
                "size": "1024x1024",
            },
        )
        if img_resp.status_code != 200:
            raise RuntimeError(f"muse-image-1.0 failed ({img_resp.status_code}): {img_resp.text[:250]}")

        img_json = img_resp.json()
        img_latency_ms = round((time.perf_counter() - t_img0) * 1000.0, 2)
        b64_webp = img_json["data"][0]["b64_json"]
        raw_webp_bytes = base64.b64decode(b64_webp)

        _record_telemetry(
            model="muse-image-1.0",
            endpoint="/v1/images/generations",
            request_id=f"img-{img_json.get('created', int(time.time()))}",
            latency_ms=img_latency_ms,
            extra={"target_id": sar_target.id},
        )

        # Convert WebP bytes to JPEG in memory for /v1/files upload
        from PIL import Image
        im = Image.open(io.BytesIO(raw_webp_bytes)).convert("RGB")
        jpeg_buf = io.BytesIO()
        im.save(jpeg_buf, format="JPEG", quality=90)
        jpeg_bytes = jpeg_buf.getvalue()

        # Step 2: Upload JPEG to `POST https://api.meta.ai/v1/files`
        t_up0 = time.perf_counter()
        up_resp = await client.post(
            f"{META_BASE_URL}/files",
            headers={"Authorization": f"Bearer {api_key}", "User-Agent": "OceanEye-MetaHackathon/1.0"},
            data={"purpose": "user_data"},
            files={"file": ("vessel_sar_capture.jpg", jpeg_bytes, "image/jpeg")},
        )
        if up_resp.status_code != 200:
            raise RuntimeError(f"/v1/files upload failed ({up_resp.status_code}): {up_resp.text[:250]}")

        file_obj = up_resp.json()
        file_id = file_obj["id"]

        # Step 3: Run `sam-3.1` segmentation on `POST https://api.meta.ai/v1/responses`
        t_sam0 = time.perf_counter()
        sam_payload = {
            "model": "sam-3.1",
            "input": [
                {
                    "type": "message",
                    "role": "user",
                    "content": [
                        {"type": "input_text", "text": prompt_target},
                        {"type": "input_image", "file_id": file_id},
                    ],
                }
            ],
            "stream": True,
            "metadata": {"mask_encoding": "lossless"},
        }
        sam_resp = await client.post(
            f"{META_BASE_URL}/responses",
            headers={
                "Authorization": f"Bearer {api_key}",
                "Content-Type": "application/json",
                "Accept": "text/event-stream",
                "User-Agent": "OceanEye-MetaHackathon/1.0",
            },
            json=sam_payload,
        )
        if sam_resp.status_code != 200:
            raise RuntimeError(f"sam-3.1 failed ({sam_resp.status_code}): {sam_resp.text[:250]}")

        sam_latency_ms = round((time.perf_counter() - t_sam0) * 1000.0, 2)
        sam_parsed = _parse_sam31_sse_output(sam_resp.text)

        _record_telemetry(
            model="sam-3.1",
            endpoint="/v1/responses",
            request_id=sam_parsed.get("response_id") or file_id,
            latency_ms=sam_latency_ms,
            extra={
                "target_id": sar_target.id,
                "file_id": file_id,
                "detections_count": sam_parsed["detections_count"],
            },
        )

        # Create a compact base64 JPEG preview (512x512) for fast UI rendering
        im_thumb = im.resize((512, 512))
        thumb_buf = io.BytesIO()
        im_thumb.save(thumb_buf, format="JPEG", quality=82)
        b64_jpeg_preview = base64.b64encode(thumb_buf.getvalue()).decode("ascii")

        total_ms = round((time.perf_counter() - t_start) * 1000.0, 2)
        return {
            "status": "success",
            "target_id": sar_target.id,
            "classification": sar_target.classification,
            "wgs84_coordinates": {"lat": sar_target.lat, "lon": sar_target.lon},
            "radar_metrics": {
                "estimated_length_m": sar_target.length_m,
                "estimated_beam_m": sar_target.beam_m,
                "peak_rcs_db": sar_target.peak_rcs_db,
                "snr_db": sar_target.snr_db,
            },
            "meta_muse_image_generation": {
                "model": "muse-image-1.0",
                "prompt": prompt,
                "latency_ms": img_latency_ms,
                "image_data_url": f"data:image/jpeg;base64,{b64_jpeg_preview}",
            },
            "meta_files_upload": {
                "file_id": file_id,
                "bytes": len(jpeg_bytes),
                "purpose": "user_data",
            },
            "meta_sam31_segmentation": {
                "model": "sam-3.1",
                "prompt_target": prompt_target,
                "latency_ms": sam_latency_ms,
                **sam_parsed,
            },
            "total_pipeline_latency_ms": total_ms,
        }


def build_sam31_box_prompt_payload(
    file_id: str,
    bbox_xyxy: Optional[List[int]] = None,
    text_prompt: Optional[str] = "ship",
    mask_encoding: str = "lossless",
    stream: bool = True,
) -> Dict[str, Any]:
    """
    Build the `sam-3.1` `/v1/responses` payload directly on a Dual-Pol SAR chip
    with optional CFAR box prompt `[x1, y1, x2, y2]` and text prompt, without
    invoking `muse-image-1.0`.
    """
    content: List[Dict[str, Any]] = []
    if text_prompt:
        content.append({"type": "input_text", "text": text_prompt})
    img_item: Dict[str, Any] = {"type": "input_image", "file_id": file_id}
    content.append(img_item)
    metadata: Dict[str, Any] = {"mask_encoding": mask_encoding}
    if bbox_xyxy and len(bbox_xyxy) == 4:
        metadata["box_prompt_xyxy"] = [int(x) for x in bbox_xyxy]
    return {
        "model": "sam-3.1",
        "input": [
            {
                "type": "message",
                "role": "user",
                "content": content,
            }
        ],
        "stream": stream,
        "metadata": metadata,
    }


async def segment_sar_chip_with_box_prompt(
    chip_png_path: str,
    bbox_xyxy: Optional[List[int]] = None,
    text_prompt: Optional[str] = "ship",
    dry_run: bool = True,
) -> Dict[str, Any]:
    """
    Pipeline CFAR -> SAR chip PNG -> `sam-3.1` box prompt (no `muse-image-1.0`).
    Defaults to `dry_run=True` (zero API cost unless explicitly authorized under Puerta A).
    """
    import hashlib

    with open(chip_png_path, "rb") as fh:
        raw_bytes = fh.read()
    chip_sha256 = hashlib.sha256(raw_bytes).hexdigest()

    if dry_run:
        payload = build_sam31_box_prompt_payload(
            file_id="file-dryrun-placeholder",
            bbox_xyxy=bbox_xyxy,
            text_prompt=text_prompt,
        )
        return {
            "mode": "dry_run",
            "api_calls_made": 0,
            "cost_usd": 0.0,
            "chip_path": chip_png_path,
            "chip_sha256": chip_sha256,
            "request_payload": payload,
        }

    raise RuntimeError(
        "Live SAM 3.1 execution on SAR chips requires explicit Puerta A spend authorization."
    )


